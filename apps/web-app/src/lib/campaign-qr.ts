import QRCode from "qrcode";

/** Shared diffusion/test QR renderer; the caller supplies the appropriate URL. */
export async function createCampaignQrSvg(url: string) {
  return QRCode.toString(url, {
    type: "svg",
    margin: 1,
    color: {
      dark: "#111827",
      light: "#ffffff",
    },
    width: 1200,
  });
}
